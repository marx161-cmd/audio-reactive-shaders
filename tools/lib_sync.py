#!/usr/bin/env python3
"""Paste shared GLSL from shaders/_lib/<name>.glsl into every consumer, between the markers

    // @lib <name> begin
    ...           (replaced on every run -- never edit in the consumer)
    // @lib <name> end

The renderer and ShaderEditor have no #include, so consumers carry the text. Usage:
    python3 tools/lib_sync.py [--check] [file ...]     (default: every .glsl/.comp under shaders/ and phone-import/)
--check exits 1 if any consumer is out of date.
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "shaders", "_lib")
check = "--check" in sys.argv
files = [a for a in sys.argv[1:] if not a.startswith("--")] or sorted(
    f for pat in ("shaders/**/*.glsl", "shaders/**/*.comp", "phone-import/*.glsl", "shaders/mobile/*.glsl")
    for f in glob.glob(os.path.join(ROOT, pat), recursive=True) if "/_lib/" not in f and "/_attic/" not in f)
mark = re.compile(r"^([ \t]*)// @lib (\w+) begin[^\n]*\n.*?^[ \t]*// @lib \2 end[^\n]*$", re.S | re.M)
stale = 0
for f in files:
    s = open(f).read()
    if "// @lib " not in s:
        continue
    def put(m):
        name = m.group(2)
        body = open(os.path.join(LIB, name + ".glsl")).read().rstrip("\n")
        return f"// @lib {name} begin (generated by tools/lib_sync.py from shaders/_lib/{name}.glsl -- edit that)\n{body}\n// @lib {name} end"
    new = mark.sub(put, s)
    if new != s:
        stale += 1
        print(("STALE " if check else "synced ") + os.path.relpath(f, ROOT))
        if not check:
            open(f, "w").write(new)
sys.exit(1 if check and stale else 0)
