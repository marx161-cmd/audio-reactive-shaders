def _g3(n):
    g = max(1, (n + 7) // 8)
    return (g, g, g)

def _zeroed2(api, n):
    t = api.texture3d((n, n, n), "rg16f")
    t.write(bytes(n * n * n * 4))
    return t

def _zeroed(api, n, fmt):
    t = api.texture3d((n, n, n), fmt)
    bpp = {"rgba16f": 8, "r32f": 4, "r16f": 2}[fmt]
    t.write(bytes(n * n * n * bpp))
    return t

