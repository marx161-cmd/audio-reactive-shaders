def _lab(s):
    """The pad's back / next press counters -> the lab move (persisted in LAB_FILE, so a reload keeps it)."""
    if "lab" not in s:
        try:
            s["lab"] = max(0, min(len(LAB_MOVES) - 1, int(open(LAB_FILE).read().strip() or 0)))
        except (OSError, ValueError):
            s["lab"] = 0
    now = time.monotonic()
    if now - s.get("lab_t", 0.0) >= 0.1:
        s["lab_t"] = now
        try:
            mt = os.stat(PAD_JSON).st_mtime_ns
            if mt != s.get("lab_mt"):
                s["lab_mt"] = mt
                trig = json.load(open(PAD_JSON)).get("derived", {}).get("trigger", {})
                cur = (int(trig.get("lab_prev", 0)), int(trig.get("lab_next", 0)))
                prev = s.get("lab_cnt")
                s["lab_cnt"] = cur
                if prev is not None:
                    step = max(0, cur[1] - prev[1]) - max(0, cur[0] - prev[0])
                    if step:
                        s["lab"] = (s["lab"] + step) % len(LAB_MOVES)
                        try:
                            open(LAB_FILE, "w").write(str(s["lab"]))
                        except OSError:
                            pass
                        name = LAB_MOVES[s["lab"]]
                        msg = f"{s['lab']} / {len(LAB_MOVES) - 1}: {name}" if s["lab"] else "off (normal choreography)"
                        print(f"ember lab: {msg}", file=sys.stderr)
        except (OSError, ValueError):
            pass
    return s["lab"]

