def _voronoi_table():
    """FORM_VDOME (scope.md 2026-10-11 mirror formations): 2 x N_LMAX unit-sphere points spaced
    evenly along the cell edges of a spherical Voronoi diagram whose seeds are mirror-symmetric
    about y = 0 (so with the water's reflection it reads as a full Voronoi ball); upper half only.
    Consecutive points run along the edges (a leader's split twins are neighbours)."""
    from scipy.spatial import SphericalVoronoi
    rng = np.random.default_rng(11)
    v = rng.normal(size=(VOR_SEEDS, 3))
    v[:, 1] = np.abs(v[:, 1]) + 0.15
    v /= np.linalg.norm(v, axis=1, keepdims=True)
    seeds = np.concatenate([v, v * np.array([1.0, -1.0, 1.0])])
    sv = SphericalVoronoi(seeds)
    edges = set()
    for reg in sv.regions:
        for a, b in zip(reg, reg[1:] + reg[:1]):
            edges.add((min(a, b), max(a, b)))
    arcs = []
    for a, b in sorted(edges):
        p, q = sv.vertices[a], sv.vertices[b]
        ang = np.arccos(np.clip(np.dot(p, q), -1.0, 1.0))
        n = max(2, int(ang / 0.01))
        t = np.linspace(0.0, 1.0, n)[:, None]
        pts = np.sin((1 - t) * ang) / np.sin(ang) * p + np.sin(t * ang) / np.sin(ang) * q if ang > 1e-6 else np.repeat(p[None], n, 0)
        pts = pts[pts[:, 1] >= VOR_YMIN]
        if len(pts) >= 2:
            arcs.append(pts)
    path = np.concatenate(arcs)
    seg = np.r_[0.0, np.cumsum(np.linalg.norm(np.diff(path, axis=0), axis=1))]
    cut = np.cumsum([len(a) for a in arcs])[:-1]
    d = np.diff(seg)
    d[cut - 1] = 0.0
    s = np.r_[0.0, np.cumsum(d)]
    n_all = 2 * N_LMAX
    target = (np.arange(n_all) + 0.5) / n_all * s[-1]
    idx = np.clip(np.searchsorted(s, target), 1, len(s) - 1)
    out = path[idx]
    tab = np.zeros((n_all, 4), dtype="f4")
    tab[:, :3] = out
    tab[:, 3] = 1.0
    return tab.tobytes()

