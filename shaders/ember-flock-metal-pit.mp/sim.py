def _air_sweeps(api, w, lvl, sweeps, wall_only):
    n = w["sizes"][lvl]
    for _ in range(sweeps):
        for parity in (0, 1):
            api.run(w["k"]["SMOOTH"], _g3(n), images={0: w["q"][lvl], 1: w["b"][lvl], 2: w["m"][lvl]},
                    uniforms={"u_n": n, "u_parity": parity, "u_wallOnly": int(wall_only), "u_eps": AIR_EPS * 4 ** lvl})

def _air_smooth(api, w, lvl, sweeps):
    _air_sweeps(api, w, lvl, AIR_WALL, True)
    _air_sweeps(api, w, lvl, sweeps, False)
    _air_sweeps(api, w, lvl, AIR_WALL, True)

def _air_vcycle(api, w, lvl=0):
    if lvl > 0 or not w["marked0"]:
        api.run(w["k"]["MARK"], _g3(w["sizes"][lvl]), images={0: w["m"][lvl]}, uniforms={"u_n": w["sizes"][lvl]})
        w["marked0"] = True
    if lvl == AIR_LEVELS - 1:
        _air_smooth(api, w, lvl, AIR_COARSE)
        return
    _air_smooth(api, w, lvl, AIR_PRE)
    nc = w["sizes"][lvl + 1]
    api.run(w["k"]["RESTRICT"], _g3(nc),
            images={0: w["q"][lvl], 1: w["b"][lvl], 2: w["m"][lvl], 3: w["q"][lvl + 1], 4: w["b"][lvl + 1], 5: w["m"][lvl + 1]},
            uniforms={"u_n": nc, "u_eps": AIR_EPS * 4 ** lvl})
    _air_vcycle(api, w, lvl + 1)
    api.run(w["k"]["PROLONG"], _g3(w["sizes"][lvl]),
            images={0: w["q"][lvl], 1: w["m"][lvl], 2: w["q"][lvl + 1], 3: w["m"][lvl + 1]},
            uniforms={"u_n": w["sizes"][lvl]})
    _air_smooth(api, w, lvl, AIR_POST)

def _air_step(api, w, dt, ctl):
    """One air step (the stir grid holds last frame's embers); w["vel"][w["cur"]] is the new velocity after it."""
    k = w["k"]
    for prog in k.values():
        api.set(prog, {"u_H": AIR_H, "u_dt": dt, "u_n": AIR_N})
    c = w["cur"]
    vel0, vel1 = w["vel"][c], w["vel"][1 - c]
    g = _g3(AIR_N)
    api.run(k["MASK"], g, images={0: w["wall"], 1: w["m"][0], 2: vel0})
    api.run(k["ADV_FWD"], g, images={0: w["vtmp"]}, samplers={"u_src": vel0, "u_vel": vel0})
    api.run(k["ADV_CORR"], g, images={0: vel1, 1: w["m"][0]}, samplers={"u_src": vel0, "u_fwd": w["vtmp"], "u_vel": vel0})
    api.run(k["FORCE"], g, images={0: vel1, 1: w["stir"]}, samplers={"u_ctl": ctl})
    sc = w["scur"]
    api.run(k["SMOKE"], _g3(SMOKE_N), images={0: w["smk"][1 - sc], 1: w["stir"]}, samplers={"u_smk": w["smk"][sc], "u_vel": vel0},
            uniforms={"u_n": SMOKE_N})
    w["scur"] = 1 - sc
    api.run(k["SCLEAR"], (8, 8, 40), images={0: w["stir"]})
    api.run(k["DIV"], g, images={0: w["b"][0], 1: vel1, 2: w["wall"]})
    w["marked0"] = False
    _air_vcycle(api, w)
    api.run(k["PROJECT"], g, images={0: vel1, 1: w["q"][0], 2: w["wall"]})
    w["cur"] = 1 - c

def _social(s):
    """The current SOCIAL setting; with TRIALS, cycle them and log efficiency per setting."""
    tr = s["trial"]
    now = time.monotonic()
    if not TRIALS:
        return SOCIAL
    idx = int((now - tr["t0"]) // TRIAL_S) % len(TRIALS)
    social = TRIALS[idx]
    if now - tr["last_read"] >= 0.25:
        tr["last_read"] = now
        a = np.frombuffer(s["fol"].read(), dtype="u4").reshape(8, N_LMAX + 1)
        n = float(a[2, N_LMAX])
        if n > 0:
            fid, spd = a[0, N_LMAX] / 1000.0 / n, a[1, N_LMAX] / 1000.0 / n
            e = tr["acc"].setdefault(str(social), {"n": 0, "fidelity": 0.0, "speed": 0.0})
            e["n"] += 1
            e["fidelity"] += (fid - e["fidelity"]) / e["n"]
            e["speed"] += (spd - e["speed"]) / e["n"]
            if e["n"] % 8 == 0:
                try:
                    with open(TRIALS_PATH + ".tmp", "w") as f:
                        json.dump({"current": social, "trial_s": TRIAL_S, "results": tr["acc"]}, f, indent=1)
                    os.replace(TRIALS_PATH + ".tmp", TRIALS_PATH)
                except OSError:
                    pass
    return social

