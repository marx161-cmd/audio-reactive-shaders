def _ktime_wrap(api, s):
    """Per-dispatch GPU timing for ONE frame every KTIME_S (a query around each api.run), printed as the top ten."""
    now = time.monotonic()
    if KTIME_S <= 0 or now - s.get("kt_last", 0.0) < KTIME_S:
        return None
    s["kt_last"] = now
    names = {id(v): k for k, v in s["k"].items()}
    names.update({id(p): "phone." + n for n, (p, g) in s["pk"].items()})
    names.update({id(v): "air." + k for k, v in s["air"]["k"].items()})
    acc, real = {}, api.run
    def run(kernel, groups, images=None, samplers=None, uniforms=None):
        q = api.ctx.query(time=True)
        with q:
            real(kernel, groups, images=images, samplers=samplers, uniforms=uniforms)
        n = names.get(id(kernel), "?")
        acc[n] = acc.get(n, 0.0) + q.elapsed / 1e6
    api.run = run
    return acc, real

def step(api, dt):
    kt = _ktime_wrap(api, api.state)
    try:
        _step(api, dt)
    finally:
        if kt:
            acc, real = kt
            api.run = real
            top = sorted(acc.items(), key=lambda kv: -kv[1])[:10]
            print("ktime: total %.1f ms | " % sum(acc.values()) + "  ".join(f"{n} {ms:.2f}" for n, ms in top), file=sys.stderr)

