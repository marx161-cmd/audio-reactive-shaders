def _init_boids():
    rng = np.random.default_rng(7)
    d = np.zeros((3, N_ALL, 4), dtype="f4")
    for f, cx in ((0, -0.3), (1, 0.3)):
        sl = slice(f * N_PER, (f + 1) * N_PER)
        v = rng.normal(size=(N_PER, 3))
        v /= np.linalg.norm(v, axis=1, keepdims=True)
        r = 0.15 * rng.random(N_PER) ** (1 / 3)
        d[0, sl, :3] = np.array([cx, 0.0, 0.0]) + v * r[:, None]
